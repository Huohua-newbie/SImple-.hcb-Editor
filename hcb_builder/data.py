def load_cg_loaded(path) -> dict:
    """从 ``cg_loaded.txt`` 读取 CG 已加载偏移表。

    文件格式：每两行一组 —— 奇数行是十六进制偏移，偶数行是带引号的 CG 名。
    返回 ``{CG名(大写): 偏移(int)}``。
    """
    with open(path, encoding="utf-8") as f:
        lines = [line.strip() for line in f if line.strip()]
    return {
        lines[i + 1].strip('"').upper(): int(lines[i], 16)
        for i in range(0, len(lines), 2)
    }
